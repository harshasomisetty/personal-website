#!/usr/bin/env python3
"""Write src/flights.json from the Flighty Mac app database (past flights of the account owner).

Run: python3 tools/flighty.py   (reads a copy; the app database is never opened for writing)
"""
import glob, json, os, shutil, sqlite3, tempfile, time
from datetime import datetime
from zoneinfo import ZoneInfo
from collections import Counter
from pathlib import Path

SRC = Path.home() / 'Library/Containers/com.flightyapp.flighty/Data/Documents/MainFlightyDatabase.db'
OUT = Path(__file__).resolve().parent.parent / 'src/flights.json'
KM_TO_MI = 0.621371

tmp = tempfile.mkdtemp()
for f in glob.glob(f'{SRC}*'):
    shutil.copy(f, tmp)
db = sqlite3.connect(os.path.join(tmp, SRC.name))
me = db.execute('select remoteId from User').fetchone()[0]  # the signed-in Flighty user

q = '''
select f.departureAirportId, f.actualArrivalAirportId, f.airlineId, f.distance, f.lastKnownDepartureDate, f.lastKnownArrivalDate
from UserFlight u join Flight f on f.id = u.flightId
where u.userId = ? and u.isMyFlight and u.deleted is null and not f.isCancelled  -- f.deleted marks a stale shared record; the app still counts the flight
union all
select m.departureAirportId, m.actualArrivalAirportId, m.airlineId, m.distance, m.lastKnownDepartureDate, m.lastKnownArrivalDate
from UserManualFlight u join ManualFlight m on m.id = u.flightId
where u.userId = ? and u.deleted is null and m.deleted is null and not m.isCancelled
'''
now = time.time()
flights = [r for r in db.execute(q, (me, me)) if r[4] < now]
airports = {r[0]: r[1:] for r in db.execute('select id, iata, city, latitude, longitude, countryCode, timeZoneIdentifier from Airport')}
airlines = {r[0]: r[1] for r in db.execute('select id, name from Airline')}

routes = Counter(tuple(sorted((airports[d][0], airports[a][0]))) for d, a, *_ in flights)
visits = Counter(airports[x][0] for d, a, *_ in flights for x in (d, a))
carriers = Counter(airlines.get(al, '?') for _, _, al, *_ in flights)
miles = sum(r[3] for r in flights) * KM_TO_MI
longest = max(flights, key=lambda r: r[3])

out = {
    'note': 'Generated by tools/flighty.py from Flighty. Past flights only.',
    'since': time.strftime('%Y-%m', time.gmtime(min(r[4] for r in flights))),
    'flights': len(flights),
    'miles': round(miles),
    'hours': round(sum(r[5] - r[4] for r in flights if r[5]) / 3600),
    'airports': len(visits),
    'airlines': len(carriers),
    'aroundEarth': round(miles / 24901, 1),
    'longest': {'from': airports[longest[0]][0], 'to': airports[longest[1]][0], 'miles': round(longest[3] * KM_TO_MI)},  # IATA codes
    'topAirports': [{'code': c, 'city': next(v[1] for v in airports.values() if v[0] == c), 'visits': n} for c, n in visits.most_common(5)],
    'topAirlines': [{'name': n, 'flights': k} for n, k in carriers.most_common(5)],
    'points': {v[0]: [round(v[3], 3), round(v[2], 3)] for k, v in airports.items() if v[0] in visits},  # [lon, lat]
    'country': {v[0]: v[4] for v in airports.values() if v[0] in visits},  # ISO alpha-2 per airport
    'routes': len(routes),
    # Every flight in date order, for the route replay: [from, to, 'YYYY-MM-DD' local departure date].
    'log': [[airports[d][0], airports[a][0], datetime.fromtimestamp(t, ZoneInfo(airports[d][5] or 'UTC')).strftime('%Y-%m-%d')]
            for d, a, _, _, t, _ in sorted(flights, key=lambda r: r[4])],
}
OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + '\n')
shutil.rmtree(tmp)
print(f"{out['flights']} flights, {out['miles']:,} mi, {out['airports']} airports, {out['routes']} routes -> {OUT}")
